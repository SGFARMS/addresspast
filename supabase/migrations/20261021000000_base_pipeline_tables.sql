-- =====================================================================
-- Base tables the existing /pipeline writes to.
-- On your existing Supabase project these already exist, and every
-- statement here is a no-op. On a fresh project it creates them so the
-- Phase 1 migration and seed script work.
-- =====================================================================

create table if not exists public.incidents (
  id                 bigint generated by default as identity primary key,
  source_url         text not null,
  source_name        text,
  published_date     date,
  incident_date      text,          -- free text from the extractor ("1932-03-08", "March 1932", "1930s")
  address_raw        text not null default '',
  city               text,
  county             text,
  location_precision text check (location_precision in ('street_address','intersection','landmark','city_only')),
  cause_category     text not null default 'unknown'
                     check (cause_category in ('natural','accident','homicide','suicide','fire','unknown')),
  summary            text,
  confidence         numeric(4,3),
  lat                double precision,
  lng                double precision,
  created_at         timestamptz not null default now(),
  unique (source_url, address_raw)
);

create table if not exists public.scanned_pages (
  url         text primary key,
  scanned_at  timestamptz not null default now()
);
